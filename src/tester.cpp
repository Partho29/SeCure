    int i = 0;
    for(auto &row : tester::TEST_COMMANDS) {
        std::cout << "TEXT " << i++ << std::endl;
        std::vector<char*> temp;
        temp.reserve((row.size()));
        for(auto &str : row) temp.push_back(str.data());
        temp.insert(temp.begin(), (char*)"1");
        parser::parse(temp.size(), temp.data());
        parser::printCOMMANDS();
        parser::COMMANDS.clear();
        std::cout << std::endl << std::endl;
    }
